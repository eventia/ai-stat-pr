import pytest

from modules.pet_stats import aggregate_sample_sales, build_indicators


def test_aggregate_sample_sales_sums_by_item_and_ranks_descending():
    표본매출 = [
        {"업체명": "A", "품목": "사료", "매출액": 4000},
        {"업체명": "B", "품목": "사료", "매출액": 3000},
        {"업체명": "C", "품목": "간식", "매출액": 2000},
    ]
    결과 = aggregate_sample_sales(표본매출)

    사료 = next(r for r in 결과 if r["품목"] == "사료")
    간식 = next(r for r in 결과 if r["품목"] == "간식")
    assert 사료["당월거래액"] == 7000  # 4000 + 3000, 코드가 직접 합산
    assert 간식["당월거래액"] == 2000
    assert 사료["순위"] == 1
    assert 간식["순위"] == 2


def test_aggregate_sample_sales_shares_sum_to_100():
    표본매출 = [
        {"업체명": "A", "품목": "사료", "매출액": 700},
        {"업체명": "B", "품목": "간식", "매출액": 200},
        {"업체명": "C", "품목": "장난감", "매출액": 100},
    ]
    결과 = aggregate_sample_sales(표본매출)
    assert round(sum(r["비중"] for r in 결과), 1) == 100.0


def test_build_indicators_computes_everything_from_raw_inputs_only():
    """표본매출·이력만 넣었을 때, 사람이 미리 계산해서 넣어준 값 없이 계산지표·
    품목별지표·통계해석결과·월별이력이 전부 올바르게 계산되는지 확인한다."""
    표본매출 = [
        {"업체명": "A", "품목": "사료", "매출액": 22000},
        {"업체명": "B", "품목": "간식", "매출액": 12000},
        {"업체명": "C", "품목": "장난감", "매출액": 8000},
        {"업체명": "D", "품목": "위생용품", "매출액": 5200},
        {"업체명": "E", "품목": "기타", "매출액": 2500},
    ]
    이력 = [
        {"연월": "2024-03", "값": 45000},
        {"연월": "2025-03", "값": 52000},
        {"연월": "2025-11", "값": 61000},
        {"연월": "2025-12", "값": 58000},
        {"연월": "2026-01", "값": 55000},
        {"연월": "2026-02", "값": 53000},
    ]

    결과 = build_indicators(표본매출, 이력, "2026-03")

    assert 결과["계산지표"]["총거래액"] == 49700
    assert 결과["계산지표"]["전월대비증감률"] == -6.2
    assert 결과["계산지표"]["전년동월대비증감률"] == -4.4
    assert 결과["역대최대여부"] is False  # 2025-03(52000) > 49700
    assert 결과["최근3개월증감률"] == [-5.2, -3.6, -6.2]
    assert "전월 대비 큰 폭 감소" in 결과["통계해석결과"]["특이점목록"]
    assert "최근 3개월 연속 감소세" in 결과["통계해석결과"]["특이점목록"]
    assert len(결과["통계해석결과"]["해석문장"]) == 2
    assert len(결과["월별이력"]) == 7  # 과거 6개월 + 이번 달
    assert 결과["월별이력"][-1] == {"연월": "2026-03", "값": 49700}


def test_build_indicators_returns_integer_typed_history_values():
    """실제 실행 중 재현된 버그의 회귀 테스트: 이력(float)과 새로 계산한 총거래액(int)을
    그대로 섞으면 pandas.DataFrame이 열 전체를 float64로 승격시켜 6차시 꺾은선그래프
    설명문에 "49,700.0억 원"처럼 ".0"이 붙고, 이게 9차시 수치교차검증 실패로 이어졌다.
    월별이력의 모든 "값"이 순수 int여야 한다."""
    표본매출 = [{"업체명": "A", "품목": "사료", "매출액": 49700}]
    이력 = [
        {"연월": "2025-03", "값": 52000.0},  # pet_input.py처럼 float으로 들어오는 상황 재현
        {"연월": "2026-02", "값": 53000.0},
    ]
    결과 = build_indicators(표본매출, 이력, "2026-03")

    for 항목 in 결과["월별이력"]:
        assert isinstance(항목["값"], int), f"{항목}의 값이 int가 아님"


def test_build_indicators_raises_when_history_missing_comparison_month():
    """전월/전년동월 데이터가 이력에 없으면 0이나 임의값으로 조용히 채우지 않고
    명확한 예외를 던져야 한다 — PLAN 문서의 '눈가림 금지' 원칙."""
    표본매출 = [{"업체명": "A", "품목": "사료", "매출액": 100}]
    이력_불충분 = [{"연월": "2020-01", "값": 999}]  # 전월도 전년동월도 아님

    with pytest.raises(ValueError, match="전월 또는 전년동월"):
        build_indicators(표본매출, 이력_불충분, "2026-03")
