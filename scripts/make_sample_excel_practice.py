"""7차 세션 실습용: 새 시나리오("반려동물용품 온라인 거래 동향") 샘플 xlsx 생성.

기존 make_sample_excel.py/make_sample_excel_full.py(온라인쇼핑 동향, 증가만 있는 예시)와는
일부러 다른 시나리오로 구성했다 — 전월 대비 큰 폭 "감소"와 "3개월 연속 감소세"가 함께
나타나도록 숫자를 설계해서, 7차 세션에서 고친 두 가지를 실습자가 직접 눈으로 확인할 수 있다.

1. modules/stats.py의 감소 방향 해석문장 (이전에는 감지만 되고 문장이 안 만들어지던 버그)
2. modules/io.py의 "이력" 시트 기반 역대최대/추세 자동 계산 (이전에는 사람이 직접 입력해야 했음)

실행: python scripts/make_sample_excel_practice.py
결과: data/raw/반려동물용품_2026_03.xlsx (시트 "요약" + "이력")
"""
import json
import os

import pandas as pd

os.makedirs("data/raw", exist_ok=True)

# ---- "이력" 시트: 과거 월별 총거래액 (이번 달 제외) ----
# 같은 달(3월) 이력: 2024-03=45000, 2025-03=52000 → 올해 3월(49700)은 이 두 값보다
# 작으므로 "역대 최대치"가 아니다 (자동 계산 결과가 False로 나와야 정상).
# 최근 3개월(2025-12→2026-01→2026-02→2026-03)은 58000→55000→53000→49700으로
# 계속 줄어들어 "3개월 연속 감소세"가 자동으로 감지되어야 한다.
이력_df = pd.DataFrame({
    "연월": ["2024-03", "2025-03", "2025-11", "2025-12", "2026-01", "2026-02"],
    "총거래액": [45000, 52000, 61000, 58000, 55000, 53000],
})

# ---- "요약" 시트: 이번 달(2026-03) 실적 ----
품목별지표 = [
    {"품목": "사료", "당월거래액": 22000, "전월거래액": 23000, "전월대비증감률": -4.3, "비중": 44.3, "순위": 1},
    {"품목": "간식", "당월거래액": 12000, "전월거래액": 11000, "전월대비증감률": 9.1, "비중": 24.1, "순위": 2},
    {"품목": "장난감", "당월거래액": 8000, "전월거래액": 9500, "전월대비증감률": -15.8, "비중": 16.1, "순위": 3},
    {"품목": "위생용품", "당월거래액": 5200, "전월거래액": 5300, "전월대비증감률": -1.9, "비중": 10.5, "순위": 4},
    {"품목": "기타", "당월거래액": 2500, "전월거래액": 3900, "전월대비증감률": -35.9, "비중": 5.0, "순위": 5},
]

총거래액 = sum(item["당월거래액"] for item in 품목별지표)  # 49700
전월총거래액 = 53000  # 이력 시트의 2026-02 값과 일치해야 함
전년동월총거래액 = 52000  # 이력 시트의 2025-03 값과 일치해야 함

전월대비증감률 = round((총거래액 - 전월총거래액) / 전월총거래액 * 100, 1)
전년동월대비증감률 = round((총거래액 - 전년동월총거래액) / 전년동월총거래액 * 100, 1)

원문 = (
    "2026년  3월   반려동물용품 온라인 거래액은   49,700억원으로   전월대비  "
    f"{전월대비증감률}%   감소하였음.(주:잠정치) 반면 전년동월대비로는  {전년동월대비증감률}%   감소한 수치이다. "
    "품목별로는 간식 거래액만 유일하게 전월 대비 증가하였다."
)

요약_df = pd.DataFrame({
    "연월": ["2026-03"],
    "제목": ["2026년 3월 반려동물용품 온라인 거래 동향"],
    "총거래액": [총거래액],
    "전월대비증감률": [전월대비증감률],
    "전년동월대비증감률": [전년동월대비증감률],
    "원문": [원문],
    "품목별지표": [json.dumps(품목별지표, ensure_ascii=False)],
})

경로 = "data/raw/반려동물용품_2026_03.xlsx"
with pd.ExcelWriter(경로) as writer:
    요약_df.to_excel(writer, sheet_name="요약", index=False)
    이력_df.to_excel(writer, sheet_name="이력", index=False)

print(f"생성 완료: {경로}")
print(f"총거래액={총거래액}, 전월대비={전월대비증감률}%, 전년동월대비={전년동월대비증감률}%")
print("이 데이터로 파이프라인을 실행하면 다음이 자동으로 계산되어야 합니다:")
print("  - 역대최대여부: False (같은 3월 기준 과거 최대 52,000 > 49,700)")
print("  - 최근3개월증감률: 3개월 모두 감소 → '최근 3개월 연속 감소세' 특이점 감지")
print("  - '전월 대비 큰 폭 감소' 특이점도 함께 감지되어야 함 (감소율 5% 이상)")
